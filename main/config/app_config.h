/*
 * Налаштування світлофора: піни, тривалості фаз, пороги датчиків.
 * Усе, що доводиться підкручувати на стенді, - лише в цьому файлі.
 */
#pragma once

#include "driver/gpio.h"

/* ---------------------------- Піни ---------------------------- */

#define LED_GREEN_GPIO      GPIO_NUM_15
#define LED_YELLOW_GPIO     GPIO_NUM_16
#define LED_RED_GPIO        GPIO_NUM_17
#define BTN_PED_GPIO        GPIO_NUM_18
#define LIGHT_SENSOR_GPIO   4           /* ADC1_CH3 на ESP32-S3 */

/* ------------------------ Тривалості фаз ---------------------- */

#define T_GREEN_MS          7000u   /* зелений */
#define T_GREEN_BLINK_MS    3000u   /* зелений миготливий */
#define T_YELLOW_MS         3000u   /* жовтий */
#define T_RED_MS            7000u   /* червоний */
#define T_RED_YELLOW_MS     2000u   /* червоний + жовтий */

#define BLINK_GREEN_MS      250u    /* напівперіод миготіння зеленого (~2 Гц) */
#define BLINK_NIGHT_MS      500u    /* напівперіод миготіння жовтого вночі (1 Гц) */

/* --------------------- Кнопка пішохода ------------------------ */

#define DEBOUNCE_MS         40u     /* підтвердження натиску */
#define RELEASE_GUARD_MS    40u     /* пауза після відпускання */
#define PED_RED_MIN_MS      2000u   /* мінімум червоного до видачі запиту */

/* ----------------------- Датчик світла ------------------------ */

#define LIGHT_POLL_MS       200u    /* період опитування ADC */
#define LIGHT_STABLE_MS     2000u   /* витримка перед зміною день/ніч */
#define LIGHT_SAMPLES       8       /* усереднення одного вимірювання */

/*
 * Пороги рівня світла з гістерезисом (0..4095, більше = світліше).
 *
 * Схема: 3V3 -- фоторезистор -- GPIO4 -- R -- GND
 *   світло  -> опір фоторезистора малий  -> напруга на GPIO4 висока (adc ~3700)
 *   закрито -> опір фоторезистора великий -> напруга на GPIO4 нижча (adc ~2050..2330)
 * Пороги взято посередині між виміряними значеннями, із запасом ~400 з кожного боку.
 * Для дільника навпаки (фоторезистор до GND) поставте LIGHT_RAW_INVERTED в 1.
 */
#define LIGHT_RAW_INVERTED  0
#define LIGHT_RAW_NIGHT     2700    /* рівень нижче - вважаємо, що темно */
#define LIGHT_RAW_DAY       3200    /* рівень вище - вважаємо, що світло */

/* ------------------------ Такт системи ------------------------ */

#define TIMER_RESOLUTION_HZ 1000000u    /* 1 тік = 1 мкс */
#define TICK_PERIOD_US      5000u       /* такт кінцевого автомата: 5 мс */

/* --------------------------- Лог ------------------------------ */

#define STATUS_LOG_MS       2000u   /* період рядка стану в консолі */
